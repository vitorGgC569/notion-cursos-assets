h('SQLite 3.46: transacoes, rollback e travas (dois arquivos temporarios)')
d = tempfile.mkdtemp(); f = os.path.join(d, 'b.db')
c1 = sqlite3.connect(f, isolation_level=None, timeout=0.2); c2 = sqlite3.connect(f, isolation_level=None, timeout=0.2)
S1 = DB('SQLite', c1); S2 = DB('SQLite', c2)
S1.run("CREATE TABLE conta (id INTEGER PRIMARY KEY, saldo INTEGER CHECK (saldo >= 0))", show=False); S1.run("INSERT INTO conta VALUES (1,100),(2,50)", show=False)
S1.run("BEGIN")
S1.run("UPDATE conta SET saldo = saldo + 150 WHERE id = 2")
S1.run("UPDATE conta SET saldo = saldo - 150 WHERE id = 1")
S1.run("ROLLBACK"); S1.run("SELECT * FROM conta ORDER BY id")
print('\nPadrao do SQLite (modo rollback journal): um escritor por vez no arquivo.')
S1.run("BEGIN IMMEDIATE"); S1.run("UPDATE conta SET saldo = saldo + 1 WHERE id = 1")
print('[outra conexao tenta escrever]'); S2.run("UPDATE conta SET saldo = saldo + 1 WHERE id = 2")
print('[outra conexao le: no modo padrao leitura passa enquanto o escritor nao fez COMMIT]'); S2.run("SELECT saldo FROM conta WHERE id = 1")
S1.run("COMMIT")
S1.run("PRAGMA journal_mode = WAL")
print('Em modo WAL, leitores nao bloqueiam o escritor e vice-versa; ainda existe um unico escritor por vez.')
S1.run("PRAGMA synchronous"); S1.run("PRAGMA journal_mode")
