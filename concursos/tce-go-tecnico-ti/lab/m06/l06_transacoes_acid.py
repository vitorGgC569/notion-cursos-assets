# L6: transacoes e ACID. Atomicidade, consistencia, isolamento e durabilidade executados de verdade em PostgreSQL (duas conexoes) e em SQLite (dois arquivos temporarios).
from common import *
import threading, time, os, sqlite3, tempfile

pg = PGServer('l06'); A = pg.conn(); B = pg.conn(); versions(A)
h('A de Atomicidade e C de Consistencia (PostgreSQL)')
A.run("CREATE TABLE conta (id INTEGER PRIMARY KEY, titular TEXT, saldo NUMERIC CHECK (saldo >= 0))", show=False)
A.run("INSERT INTO conta VALUES (1,'Ana',100),(2,'Bia',50)", show=False)
A.run("SELECT * FROM conta ORDER BY id")
sub('transferencia de 150 da Ana para a Bia: o debito viola o CHECK, e a transacao inteira deve ser desfeita')
A.run("BEGIN")
A.run("UPDATE conta SET saldo = saldo + 150 WHERE id = 2")
A.run("UPDATE conta SET saldo = saldo - 150 WHERE id = 1")
A.run("SELECT * FROM conta ORDER BY id")
A.run("ROLLBACK")
print('Depois do ROLLBACK, nada do que a transacao fez permaneceu (tudo ou nada):'); A.run("SELECT * FROM conta ORDER BY id")
sub('transferencia de 30: COMMIT confirma as duas operacoes juntas')
A.run("BEGIN"); A.run("UPDATE conta SET saldo = saldo - 30 WHERE id = 1"); A.run("UPDATE conta SET saldo = saldo + 30 WHERE id = 2"); A.run("COMMIT")
A.run("SELECT *, (SELECT SUM(saldo) FROM conta) AS total FROM conta ORDER BY id")
sub('SAVEPOINT: desfazer apenas parte da transacao')
A.run("BEGIN")
A.run("UPDATE conta SET saldo = saldo + 1 WHERE id = 1")
A.run("SAVEPOINT s1")
A.run("UPDATE conta SET saldo = saldo - 1000 WHERE id = 1")
print('Em PostgreSQL, depois de um erro a transacao fica abortada; so ROLLBACK TO SAVEPOINT a recupera:')
A.run("SELECT * FROM conta WHERE id = 1")
A.run("ROLLBACK TO SAVEPOINT s1")
A.run("SELECT * FROM conta WHERE id = 1")
A.run("COMMIT")

h('I de Isolamento: nivel READ COMMITTED (padrao do PostgreSQL)')
A.run("SHOW default_transaction_isolation")
A.run("BEGIN")
print('[sessao A]'); A.run("SELECT saldo FROM conta WHERE id = 1")
print('[sessao B altera e confirma]'); B.run("UPDATE conta SET saldo = saldo + 500 WHERE id = 1")
print('[sessao A le de novo, ainda dentro da transacao: leitura nao repetivel]'); A.run("SELECT saldo FROM conta WHERE id = 1")
A.run("COMMIT")
B.run("UPDATE conta SET saldo = saldo - 500 WHERE id = 1", show=False)

h('Isolamento: REPEATABLE READ (snapshot) e conflito de escrita')
A.run("BEGIN ISOLATION LEVEL REPEATABLE READ")
print('[sessao A]'); A.run("SELECT saldo FROM conta WHERE id = 1")
print('[sessao B altera e confirma]'); B.run("UPDATE conta SET saldo = saldo + 500 WHERE id = 1")
print('[sessao A: continua vendo o snapshot do inicio]'); A.run("SELECT saldo FROM conta WHERE id = 1")
print('[sessao A tenta atualizar a mesma linha que B ja alterou]'); A.run("UPDATE conta SET saldo = saldo + 1 WHERE id = 1")
A.run("ROLLBACK")
B.run("UPDATE conta SET saldo = saldo - 500 WHERE id = 1", show=False)

h('Leitura suja (dirty read): nao ocorre no PostgreSQL, mesmo pedindo READ UNCOMMITTED')
A.run("BEGIN ISOLATION LEVEL READ UNCOMMITTED")
B.run("BEGIN"); B.run("UPDATE conta SET saldo = 99999 WHERE id = 2")
print('[sessao A enxerga a alteracao nao confirmada de B?]'); A.run("SELECT saldo FROM conta WHERE id = 2")
B.run("ROLLBACK"); A.run("COMMIT")

h('Atualizacao perdida (lost update) e SELECT ... FOR UPDATE')
A.run("CREATE TABLE contador (id INTEGER PRIMARY KEY, v INTEGER)", show=False); A.run("INSERT INTO contador VALUES (1, 10)", show=False)
print('Sem trava: as duas sessoes leem 10 e gravam 11; a segunda soma se perde.')
A.run("BEGIN"); ra = A.run("SELECT v FROM contador WHERE id = 1", show=False)[0][0]
B.run("BEGIN"); rb = B.run("SELECT v FROM contador WHERE id = 1", show=False)[0][0]
A.run("UPDATE contador SET v = %d WHERE id = 1" % (ra + 1)); A.run("COMMIT")
B.run("UPDATE contador SET v = %d WHERE id = 1" % (rb + 1)); B.run("COMMIT")
A.run("SELECT v AS valor_final_esperado_12 FROM contador")
A.run("UPDATE contador SET v = 10", show=False)
print('\nCom SELECT ... FOR UPDATE: a segunda sessao espera a primeira terminar e le o valor novo.')
def sessao_b(res):
    B.run("BEGIN", show=False); v = B.run("SELECT v FROM contador WHERE id = 1 FOR UPDATE", show=False)[0][0]
    B.run("UPDATE contador SET v = %d WHERE id = 1" % (v + 1), show=False); B.run("COMMIT", show=False); res.append(v)
A.run("BEGIN"); va = A.run("SELECT v FROM contador WHERE id = 1 FOR UPDATE")[0][0]
res = []; t = threading.Thread(target=sessao_b, args=(res,)); t.start(); time.sleep(0.5)
print('[sessao B esta bloqueada esperando a trava de A]')
A.run("UPDATE contador SET v = %d WHERE id = 1" % (va + 1)); A.run("COMMIT"); t.join()
print('sessao B leu %s (e nao 10) e gravou %s' % (res[0], res[0] + 1))
A.run("SELECT v AS valor_final FROM contador")

h('Deadlock: duas transacoes se esperando')
A.run("CREATE TABLE lin (id INTEGER PRIMARY KEY, x INTEGER)", show=False); A.run("INSERT INTO lin VALUES (1,0),(2,0)", show=False)
A.run("SET deadlock_timeout = '200ms'", show=False); B.run("SET deadlock_timeout = '200ms'", show=False)
A.run("BEGIN", show=False); B.run("BEGIN", show=False)
A.run("UPDATE lin SET x = 1 WHERE id = 1"); B.run("UPDATE lin SET x = 1 WHERE id = 2")
out = {}
def ta():
    out['A'] = A.run("UPDATE lin SET x = 2 WHERE id = 2", show=False)
t = threading.Thread(target=ta); t.start(); time.sleep(0.3)
print('[A pede a linha 2, que B segura, e fica esperando]')
print('[B pede a linha 1, que A segura: o ciclo fecha]')
r = B.run("UPDATE lin SET x = 2 WHERE id = 1", show=False)
t.join()
print('sessao B: %s' % r); print('sessao A: UPDATE concluido depois que B foi abortada' if out['A'] == [] else 'sessao A: %s' % out['A'])
A.run("ROLLBACK", show=False); B.run("ROLLBACK", show=False)
print('O PostgreSQL detecta o ciclo e aborta uma das transacoes (codigo 40P01); a outra prossegue.')

