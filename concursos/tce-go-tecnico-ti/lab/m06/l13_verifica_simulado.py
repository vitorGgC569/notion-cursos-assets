# L13: executa de verdade as consultas dos itens do simulado autoral que dependem de resultado de SQL (SQLite e PostgreSQL).
from common import *
def go(D):
    D.run("CREATE TABLE dep (id INTEGER, nome TEXT)", show=False); D.run("INSERT INTO dep VALUES (1,'RH'),(2,'TI'),(3,'Juridico')", show=False)
    D.run("CREATE TABLE func (id INTEGER, dep_id INTEGER)", show=False); D.run("INSERT INTO func VALUES (1,1),(2,1),(3,2)", show=False)
    sub('Simulado item 11: LEFT JOIN com COUNT(f.id) e, para contraste, COUNT(*)')
    D.run("SELECT d.nome, COUNT(f.id) AS q FROM dep d LEFT JOIN func f ON f.dep_id = d.id GROUP BY d.nome ORDER BY d.nome")
    D.run("SELECT d.nome, COUNT(*) AS q_errado FROM dep d LEFT JOIN func f ON f.dep_id = d.id GROUP BY d.nome ORDER BY d.nome")
    D.run("CREATE TABLE a (x INTEGER)", show=False); D.run("INSERT INTO a VALUES (1),(2),(3)", show=False)
    D.run("CREATE TABLE b (y INTEGER)", show=False); D.run("INSERT INTO b VALUES (1),(NULL)", show=False)
    sub('Simulado item 12: NOT IN com NULL, e NOT EXISTS para contraste')
    D.run("SELECT COUNT(*) AS not_in FROM a WHERE x NOT IN (SELECT y FROM b)")
    D.run("SELECT COUNT(*) AS not_exists FROM a WHERE NOT EXISTS (SELECT 1 FROM b WHERE b.y = a.x)")
    D.run("CREATE TABLE v (c INTEGER)", show=False); D.run("INSERT INTO v VALUES (10),(20),(NULL),(30)", show=False)
    sub('Simulado item 13: COUNT(*), COUNT(c) e AVG(c) com NULL')
    D.run("SELECT COUNT(*) AS cont_todas, COUNT(c) AS cont_c, AVG(c) AS media FROM v")
    D.run("CREATE TABLE t (c TEXT)", show=False); D.run("INSERT INTO t VALUES ('a'),('b'),(NULL)", show=False)
    sub("Simulado item 15: WHERE c <> 'a' com NULL")
    D.run("SELECT COUNT(*) AS diferentes FROM t WHERE c <> 'a'")
    D.run("SELECT COUNT(*) AS diferentes_ou_nulos FROM t WHERE c <> 'a' OR c IS NULL")
    D.run("CREATE TABLE u (cpf TEXT UNIQUE)", show=False)
    sub('Simulado item 4: coluna UNIQUE aceita varios NULL; repetir o valor falha')
    for v in ["'111'", 'NULL', 'NULL', "'111'"]: D.run("INSERT INTO u VALUES (%s)" % v)
    D.run("SELECT COUNT(*) AS linhas FROM u")
